"""Generates every icon and store graphic from one ring geometry.

Run from the repository root: python3 tool/render_icons.py
Needs cairosvg and Pillow. The output is checked in; CI does not run this.
"""
import io
import math
from pathlib import Path

import cairosvg
from PIL import Image, ImageDraw, ImageFont

RES = Path('android/app/src/main/res')
STORE = Path('fastlane/metadata/android/en-US/images')
FONTS = Path('assets/fonts')

BLUE = '#1F5FD6'
PEACH = '#FFB48A'
WHITE = '#FFFFFF'

# The 108 unit canvas of an adaptive icon. Everything stays inside the
# 33 unit safe zone around the centre, so no launcher mask cuts it.
C = 54
R = 27
STROKE = 10
DOT = 9.5


def point(hour, r, c=C):
    """Noon is at the top, like on the dial in the app."""
    a = (hour - 12) / 24 * 2 * math.pi
    return c + r * math.sin(a), c - r * math.cos(a)


def arc(a, b, r, c=C):
    (x1, y1), (x2, y2) = point(a, r, c), point(b, r, c)
    large = 1 if b - a > 12 else 0
    return f'M{x1:.2f},{y1:.2f} A{r},{r} 0 {large} 1 {x2:.2f},{y2:.2f}'


DONE = arc(6.5, 13.5, R)
LIVE = arc(14, 18, R)
ALL = arc(6.5, 18, R)


def svg_mark():
    return f'''<circle cx="{C}" cy="{C}" r="{R}" fill="none" stroke="{WHITE}" stroke-opacity="0.25" stroke-width="{STROKE}"/>
<path d="{DONE}" fill="none" stroke="{WHITE}" stroke-width="{STROKE}"/>
<path d="{LIVE}" fill="none" stroke="{PEACH}" stroke-width="{STROKE}"/>
<circle cx="{C}" cy="{C}" r="{DOT}" fill="{WHITE}"/>'''


def icon_png(size, clip=''):
    # Launchers show the middle 72 units of an adaptive icon. PNGs have no such
    # mask, so they crop to about the same area and the mark looks equally big.
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="14 14 80 80">
<defs>{clip}</defs><g {'clip-path="url(#m)"' if clip else ''}>
<rect width="108" height="108" fill="{BLUE}"/>{svg_mark()}</g></svg>'''
    return cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=size)


ROUND = '<clipPath id="m"><circle cx="54" cy="54" r="40"/></clipPath>'
SQUIRCLE = '<clipPath id="m"><rect x="14" y="14" width="80" height="80" rx="16"/></clipPath>'

CIRCLE_PATH = f'M{C - R},{C} a{R},{R} 0 1 1 {2 * R},0 a{R},{R} 0 1 1 {-2 * R},0'
DOT_PATH = f'M{C - DOT},{C} a{DOT},{DOT} 0 1 1 {2 * DOT},0 a{DOT},{DOT} 0 1 1 {-2 * DOT},0'


def stroke(path, color, alpha=None):
    extra = f'\n        android:strokeAlpha="{alpha}"' if alpha else ''
    return f'''    <path
        android:pathData="{path}"
        android:strokeColor="{color}"
        android:strokeWidth="{STROKE}"{extra} />
'''


def fill(path, color):
    return f'''    <path
        android:pathData="{path}"
        android:fillColor="{color}" />
'''


def vector(comment, paths):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tool/render_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{paths}</vector>
'''


def android():
    (RES / 'mipmap-anydpi-v26').mkdir(exist_ok=True)
    (RES / 'drawable/ic_launcher_foreground.xml').write_text(
        vector(
            'Adaptive icon: the day dial.',
            stroke(CIRCLE_PATH, '#FFFFFFFF', 0.25)
            + stroke(DONE, '#FFFFFFFF')
            + stroke(LIVE, '#FF' + PEACH[1:])
            + fill(DOT_PATH, '#FFFFFFFF'),
        )
    )
    (RES / 'drawable/ic_launcher_monochrome.xml').write_text(
        vector(
            'Themed icon: the launcher tints this one.',
            stroke(CIRCLE_PATH, '#FFFFFFFF', 0.3)
            + stroke(ALL, '#FFFFFFFF')
            + fill(DOT_PATH, '#FFFFFFFF'),
        )
    )
    adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''
    for name in ('ic_launcher', 'ic_launcher_round'):
        (RES / f'mipmap-anydpi-v26/{name}.xml').write_text(adaptive)
    for folder, size in (('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)):
        (RES / f'mipmap-{folder}/ic_launcher.png').write_bytes(icon_png(size, SQUIRCLE))
        (RES / f'mipmap-{folder}/ic_launcher_round.png').write_bytes(icon_png(size, ROUND))


def text(draw, xy, string, weight, size, color):
    font = ImageFont.truetype(str(FONTS / f'Manrope-{weight}.ttf'), size)
    draw.text(xy, string, font=font, fill=color, anchor='ls')


def feature_graphic():
    """1024 x 500, no alpha channel. Drawn at twice the size and scaled down."""
    k = 2
    c, r, w = 790, 262, 54
    def a(h1, h2):
        (x1, y1), (x2, y2) = point(h1, r, 0), point(h2, r, 0)
        return f'M{x1 + c:.1f},{y1 + 250:.1f} A{r},{r} 0 {1 if h2 - h1 > 12 else 0} 1 {x2 + c:.1f},{y2 + 250:.1f}'
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 500">
<rect width="1024" height="500" fill="{BLUE}"/>
<circle cx="{c}" cy="250" r="{r}" fill="none" stroke="{WHITE}" stroke-opacity="0.2" stroke-width="{w}"/>
<path d="{a(7.5, 13)}" fill="none" stroke="{WHITE}" stroke-width="{w}"/>
<path d="{a(13.4, 17.5)}" fill="none" stroke="{PEACH}" stroke-width="{w}"/>
<circle cx="{c}" cy="250" r="150" fill="{WHITE}"/>
<rect x="{c - 42}" y="208" width="84" height="84" rx="12" fill="{BLUE}"/></svg>'''
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=1024 * k, output_height=500 * k)
    img = Image.open(io.BytesIO(png)).convert('RGB')
    d = ImageDraw.Draw(img)
    text(d, (64 * k, 205 * k), 'Timelog Book', 'ExtraBold', 60 * k, WHITE)
    text(d, (64 * k, 262 * k), 'One button. Your day, logged.', 'SemiBold', 26 * k, WHITE)
    text(d, (64 * k, 306 * k), 'No ads. No tracking.', 'SemiBold', 18 * k, '#E3ECFB')
    text(d, (64 * k, 332 * k), 'Stays on your device.', 'SemiBold', 18 * k, '#E3ECFB')
    img.resize((1024, 500), Image.LANCZOS).save(STORE / 'featureGraphic.png', optimize=True)


def store_icon():
    """512 x 512 and full bleed: Google Play rounds the corners itself."""
    Image.open(io.BytesIO(icon_png(512))).convert('RGBA').save(STORE / 'icon.png')


if __name__ == '__main__':
    android()
    store_icon()
    feature_graphic()
